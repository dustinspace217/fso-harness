"""crash_report: how a run ended when the scope, not the engine, ended it (QA SL-7 / SF-4), core
dumps still being written (QA TA-7), and gdb transcript parsing."""
import json
import subprocess

import pytest

from fsoctl import crash, scope, session


def _s(**kw):
    s = session.new_session(kind="game", binary="/bin/true", fs2path="/tmp", mods=[],
                            mission=None, renderer="opengl", width=1, height=1, switches={},
                            allow_eval=False, extra_args=[])
    for k, v in kw.items():
        setattr(s, k, v)
    session.save(s)
    return s


@pytest.fixture
def ended(monkeypatch):
    """The engine is not running, its scope is gone, and coredumpctl has nothing."""
    monkeypatch.setattr(crash.launcher, "alive", lambda sess: False)
    monkeypatch.setattr(scope, "state", lambda unit: "inactive")
    monkeypatch.setattr(crash, "_coredumps_json", lambda since: "[]")
    monkeypatch.setattr(crash, "_CORE_WAIT", 0.2)
    monkeypatch.setattr(crash, "_CORE_POLL", 0.05)


def test_a_running_record_whose_scope_is_gone_was_killed_with_it(tmp_runtime, ended):
    s = _s(status="running", engine_pid=4242)
    r = crash.report(s.id)
    assert any("killed with its scope" in h for h in r["hints"])
    assert any(f"journalctl --user -u {s.scope}.scope" in h for h in r["hints"])


def test_runtime_limit_and_oom_are_named(tmp_runtime, ended):
    a = _s(status="exited", engine_pid=1, ended_by="runtime_limit", runtime_sec=30)
    assert any("runtime limit (30 s)" in h for h in crash.report(a.id)["hints"])
    b = _s(status="exited", engine_pid=1, ended_by="oom", memory_max="2097152K",
           exit_info={"returncode": -9, "signal": "SIGKILL", "at": 1.0})
    hints = crash.report(b.id)["hints"]
    assert any("MemoryMax=2097152K" in h for h in hints)


def test_sigkill_points_at_memory_max_and_the_journal(tmp_runtime, ended):
    s = _s(status="exited", engine_pid=4242, memory_max="4194304K", ended_by="exit",
           exit_info={"returncode": -9, "signal": "SIGKILL", "at": 1.0})
    hints = crash.report(s.id)["hints"]
    assert any("MemoryMax" in h and f"journalctl --user -u {s.scope}.scope" in h for h in hints)
    # SIGKILL never dumps core, so the old "core size limits" hint pointed the wrong way.
    assert not any("core" in h.lower() and "limit" in h.lower() for h in hints)


def test_core_is_polled_for_while_systemd_coredump_writes_it(tmp_runtime, ended, monkeypatch):
    s = _s(status="exited", engine_pid=4242, binary="/x",
           exit_info={"returncode": -11, "signal": "SIGSEGV", "at": 1.0})
    entry = json.dumps([{"pid": 4242, "sig": 11, "corefile": "missing", "exe": "/x",
                         "time": 1_000_000, "size": 1}])
    answers = iter(["[]", "[]", entry])
    monkeypatch.setattr(crash, "_coredumps_json", lambda since: next(answers, entry))
    monkeypatch.setattr(crash, "_CORE_WAIT", 5.0)
    r = crash.report(s.id)
    assert r["core"] and r["core"]["signal"] == "SIGSEGV"


def test_a_core_not_there_yet_says_it_may_still_be_written(tmp_runtime, ended):
    s = _s(status="exited", engine_pid=4242,
           exit_info={"returncode": -6, "signal": "SIGABRT", "at": 1.0})
    hints = crash.report(s.id)["hints"]
    assert any("may still be in progress" in h for h in hints)



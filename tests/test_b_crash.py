_CORE = {"pid": 321342, "exe": "/x/fs2_open", "time": 1791802266.278, "corefile": "present"}


def test_backtrace_debugs_exactly_the_matched_dump(monkeypatch):
    # CR2-12 / Y-11: `coredumpctl debug <pid>` opens the NEWEST dump with that pid, which after
    # pid reuse is someone else's, although the metadata was matched on pid + exe + time.
    # coredumpctl ANDs matches on different fields (checked: a wrong exe or a time window
    # outside the dump finds nothing).
    cmds = []
    monkeypatch.setattr(crash.subprocess, "run", lambda cmd, **kw: cmds.append(cmd) or
                        subprocess.CompletedProcess(cmd, 0, stdout="", stderr=""))
    crash._backtrace(_CORE)
    cmd = cmds[0]
    assert "COREDUMP_PID=321342" in cmd and "COREDUMP_EXE=/x/fs2_open" in cmd
    assert "--since=@1791802266" in cmd and "--until=@1791802267" in cmd
    assert "321342" not in cmd          # never a bare pid match


def test_backtrace_keeps_only_frame_lines(monkeypatch):
    def fake_run(cmd, **kw):
        assert kw["env"]["DEBUGINFOD_URLS"] == ""      # never fetch symbols over the network
        return subprocess.CompletedProcess(cmd, 0, stdout=GDB_TRANSCRIPT, stderr="")
    monkeypatch.setattr(crash.subprocess, "run", fake_run)
    frames = crash._backtrace(_CORE)
    assert len(frames) == 5 and all(f.startswith("#") for f in frames)
    assert frames[-1].endswith("at freespace2/freespace.cpp:4567")


def test_backtrace_is_none_when_gdb_prints_no_frames(monkeypatch):
    monkeypatch.setattr(crash.subprocess, "run",
                        lambda cmd, **kw: subprocess.CompletedProcess(cmd, 1, stdout="", stderr=""))
    assert crash._backtrace(_CORE) is None


def _rows(**over):
    """coredumpctl --json=short rows: one core for pid 4242 (time is in microseconds)."""
    row = {"time": 1_000_010_000_000, "pid": 4242, "sig": 11, "corefile": "present",
           "exe": "/x/fs2_open", "size": 1}
    row.update(over)
    return json.dumps([row])


def test_a_core_from_another_program_with_the_same_pid_is_not_ours():
    # Cross-family XK-7: pids are reused, so pid alone can attribute someone else's core.
    assert crash.parse_coredumpctl(_rows(exe="/usr/bin/other"), 4242, exe="/x/fs2_open") is None
    assert crash.parse_coredumpctl(_rows(), 4242, exe="/x/fs2_open")["pid"] == 4242


def test_a_core_logged_long_after_the_exit_is_not_ours():
    # coredumpctl's "time" is when the dump was logged, which trails the crash: 7 s for the
    # 700 MB debug core in tests/data (crash 03:50:59, logged 03:51:06). So the bound allows a
    # grace period after exit_info["at"] rather than requiring time <= at.
    at = 1_000_000.0
    late = _rows(time=int((at + crash._CORE_LOG_GRACE + 60) * 1e6))
    soon = _rows(time=int((at + 7) * 1e6))
    assert crash.parse_coredumpctl(late, 4242, exe="/x/fs2_open", exited_at=at) is None
    assert crash.parse_coredumpctl(soon, 4242, exe="/x/fs2_open", exited_at=at) is not None


def test_report_matches_the_core_on_the_sessions_binary(tmp_runtime, ended, monkeypatch):
    s = _s(status="exited", engine_pid=4242, binary="/x/fs2_open",
           exit_info={"returncode": -11, "signal": "SIGSEGV", "at": 1_000_005.0})
    monkeypatch.setattr(crash, "_coredumps_json",
                        lambda since: _rows(exe="/usr/bin/other", corefile="missing"))
    assert crash.report(s.id)["core"] is None
    monkeypatch.setattr(crash, "_coredumps_json", lambda since: _rows(corefile="missing"))
    assert crash.report(s.id)["core"]["exe"] == "/x/fs2_open"
